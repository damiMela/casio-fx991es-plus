package com.damimela.fx991.model

/** Every physical key of the keypad (hardware keyboard events are mapped onto these as well). */
enum class Key {
    SHIFT, ALPHA, LEFT, RIGHT, UP, DOWN, OPTN, MODE, ON,
    CALC, INTEGRAL, INV, LOGA,
    FRAC, SQRT, SQUARE, POW, LOG, LN,
    NEG, DMS, HYP, SIN, COS, TAN,
    RCL, ENG, LPAR, RPAR, SD, MPLUS,
    D7, D8, D9, DEL, AC,
    D4, D5, D6, MUL, DIV,
    D1, D2, D3, ADD, SUB,
    D0, DOT, EXP10, ANS, EQ
}
